"""Write the MOOSE multigroup-diffusion include file of the GFMR from the OpenMC constants.

Reads xs/gfmr_8g.json (written by openmc/postprocess.py) and writes xs/gfmr_xs.i, a HIT include
with the RealEigenVector / RealEigenMatrix constants used by gfmr_diffusion_rz.i and the
transient inputs:

  D_core, D_refl                  diffusion coefficients (cm units converted to m)
  REM_core, REM_refl              removal operator: diag(absorption + out-scatter) - in-scatter
  NSF_core                        nu Sigma_f
  KSF_core                        kappa Sigma_f (J/m)
  CHI_P, CHI_D                    prompt / delayed spectra (delayed: one spectrum for all groups)
  BETA, LAMBDA                    6-group precursor fractions and decay constants
  INV_V_core, INV_V_refl          1/v (s/m)
  VAC_ALPHA                       Marshak vacuum coefficient (1/2)

Diffusion form solved by MOOSE (array variable phi, one component per group g):
  -div(D_g grad phi_g) + (Sigma_t,g - Sigma_s,g->g) phi_g - sum_{g'!=g} Sigma_s,g'->g phi_g'
      = (1/k) chi_g sum_g' nu Sigma_f,g' phi_g'
Here Sigma_t - Sigma_s,gg is written as Sigma_a + sum_{g'!=g} Sigma_s,g->g' (removal), so that
only absorption and the off-diagonal scattering enter: R = diag(Sigma_a + out-scatter) - S_offdiag.

Usage: python make_diffusion_input.py [--json xs/gfmr_8g.json] [--out xs/gfmr_xs.i]
"""

import argparse
import json
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))


def fmt_vec(v):
    return ' '.join('%.10g' % x for x in v)


def fmt_mat(m):
    return '; '.join(fmt_vec(r) for r in m)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--json', default=os.path.join(HERE, 'xs', 'gfmr_8g.json'))
    ap.add_argument('--out', default=os.path.join(HERE, 'xs', 'gfmr_xs.i'))
    ap.add_argument('--rod-factor', type=float, default=1.0,
                    help='scale of the Hf absorber removal matrix (black-absorber correction)')
    args = ap.parse_args()
    d = json.load(open(args.json))
    G = d['num_groups']
    cm = 0.01  # OpenMC cross sections are per cm; the MOOSE model is in metres

    lines = ['# Generated by make_diffusion_input.py from %s -- do not edit.' % os.path.basename(
        args.json),
             '# 8-group (CASMO-8, fast first) constants, SI units (m, 1/m, J/m, s).',
             'num_groups = %d' % G]
    for region, tag in (('core', 'core'), ('reflector', 'refl')):
        r = d[region]
        D = np.asarray(r['D']) * cm
        sa = np.asarray(r['sigma_a']) / cm
        S = np.asarray(r['sigma_s']) / cm          # [g_from][g_to]
        Soff = S.copy()
        np.fill_diagonal(Soff, 0.0)
        out_scatter = Soff.sum(axis=1)              # leaving g by scattering to g' != g
        # removal operator R[g_to][g_from] applied to phi: R phi = diag(removal) phi - S^T phi
        R = np.diag(sa + out_scatter) - Soff.T
        lines.append('D_%s = \'%s\'' % (tag, fmt_vec(D)))
        lines.append('REM_%s = \'%s\'' % (tag, fmt_mat(R)))
        lines.append('INV_V_%s = \'%s\'' % (tag, fmt_vec(np.asarray(r['inv_v']) / cm)))
        if region == 'core':
            nsf = np.asarray(r['nu_sigma_f']) / cm
            ksf = np.asarray(r['kappa_sigma_f']) / cm * 1.602176634e-19  # eV/cm -> J/m
            chi_p = np.asarray(d['chi_prompt'])
            chi_p = chi_p / chi_p.sum()
            beta = np.asarray(d['beta_eff'])
            beta_tot = beta.sum()
            # fission operator F[g_to][g_from] = chi_g nu Sigma_f,g' (total chi for the eigenvalue)
            cd = np.asarray(d['chi_delayed'])
            cd = cd.reshape(-1, G) if cd.ndim > 1 else np.tile(cd, (6, 1))
            chi_d = (cd * beta[:, None]).sum(axis=0) / beta_tot
            chi_d = chi_d / chi_d.sum()
            chi_t = (1 - beta_tot) * chi_p + beta_tot * chi_d
            lines.append('NSF_core = \'%s\'' % fmt_vec(nsf))
            lines.append('KSF_core = \'%s\'' % fmt_vec(ksf))
            lines.append('CHI_P = \'%s\'' % fmt_vec(chi_p))
            lines.append('CHI_D = \'%s\'' % fmt_vec(chi_d))
            lines.append('F_total = \'%s\'' % fmt_mat(np.outer(chi_t, nsf)))
            lines.append('F_total_neg = \'%s\'' % fmt_mat(-np.outer(chi_t, nsf)))
            lines.append('F_prompt = \'%s\'' % fmt_mat(np.outer((1 - beta_tot) * chi_p, nsf)))
            lines.append('BETA = \'%s\'' % fmt_vec(beta))
            lines.append('BETA_TOT = %.10g' % beta_tot)
            lines.append('LAMBDA = \'%s\'' % fmt_vec(d['decay_constants']))
            lines.append('GEN_TIME = %.10g' % d['generation_time'])
    # Heterogeneous constants for the 3-D sector model: one set per OpenMC cell region
    if 'regions' in d:
        for name, r in d['regions'].items():
            D = np.minimum(np.asarray(r['D']) * cm, 0.5)    # He gaps: cap D (void, 1 mm thick)
            sa = np.asarray(r['sigma_a']) / cm
            S = np.asarray(r['sigma_s']) / cm
            Soff = S.copy()
            np.fill_diagonal(Soff, 0.0)
            R = np.diag(sa + Soff.sum(axis=1)) - Soff.T
            if name == 'cr_rod':
                R = R * args.rod_factor
            lines.append('D_%s = \'%s\'' % (name, fmt_vec(D)))
            lines.append('REM_%s = \'%s\'' % (name, fmt_mat(R)))
            nsf = np.asarray(r['nu_sigma_f']) / cm
            if nsf.max() > 0:
                lines.append('FN_%s = \'%s\'' % (name, fmt_mat(-np.outer(chi_t, nsf))))
                lines.append('KSF_%s = \'%s\'' % (name, fmt_vec(
                    np.asarray(r['kappa_sigma_f']) / cm * 1.602176634e-19)))
                lines.append('NSF_%s = \'%s\'' % (name, fmt_vec(nsf)))
    # Marshak vacuum (zero incoming partial current): -D dphi/dn = phi/2. ArrayVacuumBC adds
    # alpha phi to the weak form, so alpha = 1/2 in every group.
    lines.append('ROD_FACTOR = %.10g' % args.rod_factor)
    lines.append('VAC_ALPHA = \'%s\'' % fmt_vec([0.5] * G))
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote', args.out)


if __name__ == '__main__':
    main()
